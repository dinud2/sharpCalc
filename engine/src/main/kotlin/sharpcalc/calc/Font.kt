/** What each token looks like on the LCD. */
object Disp {
    private val MAP = mapOf(
        "neg" to "-", "-" to "−", "*" to "×", "/" to "÷", "E" to "ᴇ", "Ans" to "ANS", "nCr" to "ᴄ", "nPr" to "ᴘ",
        "x√" to "ˣ√", "pk" to "k", "pM" to "M", "pG" to "G", "pT" to "T", "pm" to "m", "pμ" to "μ", "pn" to "n", "pp" to "p", "pf" to "f",
        "hA" to "A", "hB" to "B", "hC" to "C", "hD" to "D", "hE" to "E", "hF" to "F",
    )
    val SUPER = mapOf("²" to "2", "³" to "3", "⁻¹" to "-1")

    fun text(id: String): String {
        MAP[id]?.let { return it }
        if (id.startsWith("st:")) return id.substring(3)
        if (id.length == 3 && id[0] == 'k' && id[1].isDigit()) return Consts.list[id.substring(1).toInt() - 1].sym
        if (id.length == 4 && id.startsWith("cv")) return Consts.conv[id.substring(2).toInt() - 1].let { it.from + "►" + it.to }
        return id
    }
}
